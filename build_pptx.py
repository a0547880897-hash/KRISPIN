def rtl(p, align=PP_ALIGN.RIGHT):
    pPr = p._p.get_or_add_pPr()
    pPr.set('rtl','1')
    if align==PP_ALIGN.RIGHT: pPr.set('algn','r')
    elif align==PP_ALIGN.CENTER: pPr.set('algn','ctr')

def bgfill(slide, color=BG):
    el = slide.background.element
    # set solid fill on slide bg
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = color

def box(slide, l,t,w,h, fill=None, line=None):
    from pptx.enum.shapes import MSO_SHAPE
    sp = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, l,t,w,h)
    sp.shadow.inherit=False
    if fill is None: sp.fill.background()
    else:
        sp.fill.solid(); sp.fill.fore_color.rgb=fill
    if line is None: sp.line.fill.background()
    else:
        sp.line.color.rgb=line; sp.line.width=Pt(0.75)
    return sp

def rule(slide, l,t,w, color=GOLD, h=Pt(3)):
    from pptx.enum.shapes import MSO_SHAPE
    sp=slide.shapes.add_shape(MSO_SHAPE.RECTANGLE,l,t,w,h)
    sp.shadow.inherit=False; sp.fill.solid(); sp.fill.fore_color.rgb=color; sp.line.fill.background()
    return sp

def tb(slide,l,t,w,h):
    b=slide.shapes.add_textbox(l,t,w,h); tf=b.text_frame
    tf.word_wrap=True
    tf.margin_left=Pt(4); tf.margin_right=Pt(4); tf.margin_top=Pt(2); tf.margin_bottom=Pt(2)
    return tf

def run(p, text, size=16, color=INK, bold=False, italic=False):
    r=p.add_run(); r.text=text; f=r.font
    f.size=Pt(size); f.color.rgb=color; f.bold=bold; f.italic=italic
    f.name='Arial'
    return r

def title_slide(title, subtitle=None, tag=None):
    s=prs.slides.add_slide(BLANK); bgfill(s)
    rule(s, Inches(8.6), Inches(2.0), Inches(4.2), GOLD, Pt(4))
    tf=tb(s, Inches(0.6), Inches(2.2), Inches(12.1), Inches(2.6))
    p=tf.paragraphs[0]; rtl(p); run(p,title,40,WHITE,True)
    if subtitle:
        p2=tf.add_paragraph(); rtl(p2); p2.space_before=Pt(10); run(p2,subtitle,18,MUT)
    if tag:
        p3=tf.add_paragraph(); rtl(p3); p3.space_before=Pt(14); run(p3,tag,14,GOLD,True)
    return s

def header(s, title):
    bgfill(s)
    tf=tb(s, Inches(0.5), Inches(0.28), Inches(12.3), Inches(0.95))
    p=tf.paragraphs[0]; rtl(p); run(p,title,26,WHITE,True)
    rule(s, Inches(0.5), Inches(1.18), Inches(12.3), RGBColor(0x33,0x41,0x5a), Pt(2))

def content_slide(title, blocks):
    """blocks: list of tuples:
       ('meta', text) | ('h', text) | ('b', text) | ('p', text) |
       ('q', text) | ('badge', [(txt,color),...]) | ('runs',[(txt,color,bold),...]) | ('sp',)
    """
    s=prs.slides.add_slide(BLANK); header(s,title)
    tf=tb(s, Inches(0.55), Inches(1.35), Inches(12.25), Inches(5.8))
    first=True
    for blk in blocks:
        kind=blk[0]
        p = tf.paragraphs[0] if first else tf.add_paragraph()
        first=False
        rtl(p)
        if kind=='meta':
            p.space_after=Pt(4); run(p,blk[1],12,MUT,italic=True)
        elif kind=='h':
            p.space_before=Pt(8); p.space_after=Pt(2); run(p,blk[1],17,GOLD,True)
        elif kind=='b':
            p.space_after=Pt(3); run(p,'•  '+blk[1],15,INK)
        elif kind=='p':
            p.space_after=Pt(3); run(p,blk[1],15,INK)
        elif kind=='q':
            p.space_after=Pt(4); p.space_before=Pt(2)
            run(p,'„ '+blk[1]+' ”',14,BLUE,italic=True)
        elif kind=='badge':
            p.space_after=Pt(3)
            for i,(txt,col) in enumerate(blk[1]):
                if i: run(p,'   ',13,MUT)
                run(p,'［'+txt+'］',13,col,True)
        elif kind=='runs':
            p.space_after=Pt(3)
            for (txt,col,bold) in blk[1]:
                run(p,txt,15,col,bold)
        elif kind=='sp':
            run(p,' ',6,INK)
    return s

